import { renderPdf } from './pdf';
import { brandHeader, footer, naira, row, type Brand } from './layout';

export interface ReceiptData {
  org: Brand & { logo: Buffer | null };
  receiptNo: string;
  issuedOn: string;
  booking: {
    ref: string;
    unitName: string;
    propertyName: string;
    checkIn: string;
    checkOut: string;
    nights: number;
  };
  guestName: string;
  entryLabel: string;
  amountKobo: number;
  method: string;
  reference: string | null;
  balanceAfterKobo: number;
  depositHeldKobo: number;
}

const d = (iso: string) =>
  new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-NG', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'UTC',
  });

/** Branded receipt for one payment or deposit (PAY-06, ORG-03). */
export function renderReceipt(r: ReceiptData, opts: { compress?: boolean } = {}) {
  return renderPdf(
    (doc) => {
      brandHeader(doc, r.org);
      doc.font('bold').fontSize(20).text('Receipt', 48);
      doc
        .font('body')
        .fontSize(10)
        .text(`${r.receiptNo}  ·  ${d(r.issuedOn)}`)
        .moveDown();
      row(doc, 'Guest', r.guestName);
      row(doc, 'Booking', r.booking.ref);
      row(doc, 'Stay', `${r.booking.unitName}, ${r.booking.propertyName}`);
      row(
        doc,
        'Dates',
        `${d(r.booking.checkIn)} – ${d(r.booking.checkOut)} (${r.booking.nights} night${r.booking.nights === 1 ? '' : 's'})`,
      );
      doc.moveDown();
      row(doc, r.entryLabel, naira(r.amountKobo), { bold: true });
      row(doc, 'Paid by', r.method + (r.reference ? ` · ${r.reference}` : ''));
      doc.moveDown();
      row(
        doc,
        r.balanceAfterKobo < 0 ? 'Overpaid' : 'Balance remaining',
        naira(Math.abs(r.balanceAfterKobo)),
        { bold: true },
      );
      if (r.depositHeldKobo > 0) row(doc, 'Refundable caution deposit held', naira(r.depositHeldKobo));
      footer(doc, `Thank you for staying with ${r.org.name}. Generated by Boogbe.`);
    },
    {
      ...opts,
      subject: [r.receiptNo, r.booking.ref, r.guestName, r.org.name].join(' | '),
      createdAt: new Date(`${r.issuedOn}T00:00:00Z`), // deterministic bytes per receipt
    },
  );
}
